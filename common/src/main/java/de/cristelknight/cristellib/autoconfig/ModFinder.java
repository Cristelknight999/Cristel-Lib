package de.cristelknight.cristellib.autoconfig;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import de.cristelknight.cristellib.Constants;
import de.cristelknight.cristellib.CristelLibRegistry;
import de.cristelknight.cristellib.StructureConfig;
import de.cristelknight.cristellib.config.ConfigType;
import de.cristelknight.cristellib.config.simple.ConfigRegistry;
import de.cristelknight.cristellib.util.FileHelper;
import de.cristelknight.cristellib.util.JsonHelper;
import net.minecraft.resources.Identifier;
import net.minecraft.util.GsonHelper;

import java.nio.file.Path;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

public class ModFinder {

    public static final Set<String> SUPPORTED_PLACEMENTS = Set.of("minecraft:random_spread",
            "moogs_structures:advanced_random_spread", "mes:advanced_random_spread", "mns:advanced_random_spread", "mss:advanced_random_spread", "mvs:advanced_random_spread",
            "repurposed_structures:advanced_random_spread"
    );

    public static void addAutoConfigs(String modId, Set<String> structureSets, Map<String, Set<StructureConfig>> structureConfigData, CristelLibRegistry registry) {
        Set<StructureConfig> configSet = new HashSet<>();

        boolean customPath = ACInfoData.currentData.containsKey(modId) && !ACInfoData.currentData.get(modId).autoConfigPath().isEmpty();
        String customSubPath = ConfigRegistry.get(ACConfig.class).autoConfigSubPath();

        StructureConfig edConfig = StructureConfig.createWithDefaultConfigPath(customPath ? ACInfoData.currentData.get(modId).autoConfigPath() : customSubPath + modId, "structure_toggle_config", ConfigType.TOGGLE);
        StructureConfig placementConfig = StructureConfig.createWithDefaultConfigPath(customPath ? ACInfoData.currentData.get(modId).autoConfigPath() : customSubPath + modId, "structure_placement_config", ConfigType.PLACEMENT);

        structureSets.forEach(path -> {
            JsonElement e = JsonHelper.getElement(modId, path);
            if (e != null) {

                JsonObject object = GsonHelper.convertToJsonObject(e, "Set at: " + path + " modId: " + modId).getAsJsonObject("placement");
                Identifier location = getLocation(Path.of(path));

                if (SUPPORTED_PLACEMENTS.contains(GsonHelper.getAsString(object, "type")))
                    registry.registerSetToConfig(modId, location, edConfig, placementConfig);
                else
                    registry.registerSetToConfig(modId, location, edConfig);

            }
        });

        if (placementConfig.setsNotEmpty()) configSet.add(placementConfig);
        if (edConfig.setsNotEmpty()) configSet.add(edConfig);
        if (!configSet.isEmpty()) {
            configSet.forEach((config) -> {
                config.setDefaultNamespace();
                config.setAutoGenerated();
                config.setHeader("Automatically generated by Cristel Lib");
            });
            structureConfigData.put(modId, configSet);
        }
    }


    private static Identifier getLocation(Path rootPath) {
        String namespace = rootPath.getName(1).toString();
        String rawPath = FileHelper.cutFileType(rootPath.subpath(4, rootPath.getNameCount()));
        String path = FileHelper.normalizeResourcePath(rawPath);

        if (namespace.equals(Constants.MC_ID)) {
            return Identifier.withDefaultNamespace(path);
        }
        return Identifier.fromNamespaceAndPath(namespace, path);
    }

    public static boolean shouldSkipModForACPre(String modId, Set<String> modsWithConfig) {
        return modsWithConfig.contains(modId) || modId.equals(Constants.MC_ID);
    }

    public static boolean shouldSkipModForACAfter(String modId, Set<String> modsWithConfig) {
        ACConfig acConfig = ConfigRegistry.get(ACConfig.class);
        return acConfig.disableAutoConfig() || acConfig.blacklistedMods().contains(modId) || modsWithConfig.contains(modId);
    }
}
